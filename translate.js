// Function to translate page
function getTranslate(lang) {
    // Find all elements with data-i18n attribute
    const elements = document.querySelectorAll('[data-i18n]');
    
    // Translate each element
    elements.forEach(element => {
        const key = element.dataset.i18n;
        if (i18Obj[lang] && i18Obj[lang][key]) {
            // Check if element is input with placeholder
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                if (element.hasAttribute('placeholder')) {
                    element.placeholder = i18Obj[lang][key];
                }
            } else {
                element.textContent = i18Obj[lang][key];
            }
        }
    });
    
    // Update language in HTML tag
    document.documentElement.lang = lang;
    
    // Save language preference to localStorage
    localStorage.setItem('preferred-language', lang);
    
    // Update active language button
    updateLanguageButtons(lang);
}

// Function to update active language button style
function updateLanguageButtons(lang) {
    const langButtons = document.querySelectorAll('.lang-switcher button');
    langButtons.forEach(btn => {
        if (btn.dataset.lang === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
    // Get saved language or default to 'en'
    const savedLang = localStorage.getItem('preferred-language') || 'en';
    getTranslate(savedLang);
});

